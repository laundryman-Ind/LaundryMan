// Generate src/services/vfs-lite.js — a trimmed pdfmake font set containing
// ONLY the fonts the invoice uses (Roboto-Regular + Roboto-Medium for bold).
// The full vfs_fonts.js ships four fonts (~855 KB); dropping the italic
// variants keeps the app bundle small.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const full = readFileSync(join(here, '../node_modules/pdfmake/build/vfs_fonts.js'), 'utf8')

// vfs_fonts.js is a CJS module: `var vfs = { "Roboto-Italic.ttf": "...", ... }`
// Base64 data never contains braces, so the FIRST '}' after the opening '{'
// is the object's closing brace.
const match = full.match(/var vfs\s*=\s*(\{[\s\S]*?\})/)
if (!match) throw new Error('Could not parse vfs_fonts.js')
const vfs = eval(`(${match[1]})`)

const KEEP = ['Roboto-Regular.ttf', 'Roboto-Medium.ttf']
const lite = {}
for (const name of KEEP) {
  if (!vfs[name]) throw new Error(`Missing font in vfs: ${name}`)
  lite[name] = vfs[name]
}

const out = `// Auto-generated by scripts/make-vfs-lite.mjs — do not edit by hand.\n` +
  `// Trimmed pdfmake font set (${KEEP.join(', ')}) so the app bundle stays small.\n` +
  `export default ${JSON.stringify(lite)}\n`
writeFileSync(join(here, '../src/services/vfs-lite.js'), out)
const sizeKB = Math.round(Buffer.byteLength(out) / 1024)
console.log(`wrote src/services/vfs-lite.js (${sizeKB} KB, ${KEEP.length} fonts; full vfs was ${Math.round(Buffer.byteLength(full) / 1024)} KB)`)
